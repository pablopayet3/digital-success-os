"""Exploratory analysis: who the accounts are, and whether the signals mean anything.

Synthetic data, fictional company.

Run with:  uv run python -m analytics.eda

Writes docs/eda-report.md. The questions it answers:
  1. What does the customer base look like?
  2. How does usage differ by segment?
  3. Do the signals predict outcomes? (churn and expansion in the following 90 days)
  4. Does the health score separate accounts that churn from those that stay?
  5. Do the scores track the simulator's hidden truth? (validation only)
  6. What did data quality catch?

Question 5 is the only place in the project that reads data/ground_truth/. It is a
check on the models, never an input to them.
"""

from __future__ import annotations

from pathlib import Path

import duckdb
import pandas as pd

from common.paths import DATA_DIR, ROOT
from ingest.load import warehouse_path

REPORT_PATH = ROOT / "docs" / "eda-report.md"


def table(frame: pd.DataFrame) -> list[str]:
    """A DataFrame as a Markdown table."""
    header = "| " + " | ".join(str(column) for column in frame.columns) + " |"
    divider = "|" + "---|" * len(frame.columns)
    body = ["| " + " | ".join(str(value) for value in row) + " |" for row in frame.to_numpy()]
    return [header, divider, *body, ""]


def write_report(data_dir: Path = DATA_DIR, report_path: Path = REPORT_PATH) -> Path:
    con = duckdb.connect(str(warehouse_path(data_dir)))

    def query(sql: str) -> pd.DataFrame:
        return con.execute(sql).df()

    test_day = con.execute(
        "SELECT max(snapshot_date) FROM gold.fct_outcome_labels WHERE outcome_observed"
    ).fetchone()[0]
    lines = [
        "# Exploratory analysis",
        "",
        "Synthetic data, fictional company. Generated by `analytics/eda.py`.",
        "",
        "## 1. The customer base today",
        "",
        *table(query(
            """
            SELECT coverage_tier, segment, count(*) AS accounts, sum(arr) AS arr,
                   round(avg(seats_licensed)) AS avg_seats
            FROM gold.account_current GROUP BY ALL ORDER BY coverage_tier, segment
            """
        )),
        "Lifecycle stage by coverage tier:",
        "",
        *table(query(
            """
            PIVOT (SELECT coverage_tier, lifecycle_stage FROM gold.account_current)
            ON lifecycle_stage USING count(*) GROUP BY coverage_tier ORDER BY coverage_tier
            """
        )),
        "## 2. Usage and health by segment",
        "",
        *table(query(
            """
            SELECT segment,
                   round(avg(mau_30d / seats_assigned), 2) AS active_seat_share,
                   round(avg(seat_utilisation), 2) AS seat_utilisation,
                   round(avg(prerequisite_closure_pct), 2) AS setup_closure,
                   round(avg(health_score), 1) AS health_score,
                   round(avg(assist_credits_30d) FILTER (WHERE has_assist)) AS assist_credits_30d
            FROM gold.account_current GROUP BY segment ORDER BY segment
            """
        )),
        "Behaviour clusters (k-means on six usage features), with what makes each distinct:",
        "",
        *table(query(
            """
            SELECT behaviour_cluster, count(*) AS accounts,
                   round(avg(mau_30d / seats_assigned), 2) AS active_seat_share,
                   round(avg(tickets_30d), 1) AS tickets_30d,
                   round(avg(health_score), 1) AS health_score
            FROM gold.account_current GROUP BY behaviour_cluster ORDER BY accounts DESC
            """
        )),
        "## 3. Do the signals predict outcomes?",
        "",
        f"Accounts on {test_day} (the latest day with a fully observed 90-day outcome), split",
        "by whether each signal was firing. Lift is the rate with the signal divided by the",
        "rate across all accounts. A signal built for churn should lift churn; one built for",
        "expansion should lift expansion.",
        "",
        *table(query(
            f"""
            WITH day AS (
                SELECT labels.account_id, labels.churned_within_90d, labels.expanded_within_90d
                FROM gold.fct_outcome_labels AS labels
                WHERE labels.snapshot_date = DATE '{test_day}'
            ),
            base AS (
                SELECT avg(churned_within_90d::INT) AS churn,
                       avg(expanded_within_90d::INT) AS expand
                FROM day
            )
            SELECT signals.signal_id AS signal,
                   count(*) AS accounts,
                   round(100 * avg(day.churned_within_90d::INT), 1) AS churn_pct,
                   round(avg(day.churned_within_90d::INT) / any_value(base.churn), 1) AS churn_lift,
                   round(100 * avg(day.expanded_within_90d::INT), 1) AS expansion_pct,
                   round(avg(day.expanded_within_90d::INT) / any_value(base.expand), 1)
                       AS expansion_lift
            FROM gold.signals AS signals
            INNER JOIN day ON signals.account_id = day.account_id
            CROSS JOIN base
            WHERE signals.snapshot_date = DATE '{test_day}'
            GROUP BY signals.signal_id
            ORDER BY churn_lift DESC
            """
        )),
        "Note: the two model signals are in-sample here only in part. The models were trained",
        "on earlier snapshots of mostly the same accounts; the model cards give the clean test.",
        "",
        "## 4. Does the health score separate churners?",
        "",
        *table(query(
            f"""
            SELECT facts.health_band, count(*) AS accounts,
                   round(100 * avg(labels.churned_within_90d::INT), 1) AS churned_within_90d_pct,
                   round(100 * avg(labels.expanded_within_90d::INT), 1) AS expanded_within_90d_pct
            FROM gold.account_daily AS facts
            INNER JOIN gold.fct_outcome_labels AS labels
                ON facts.account_id = labels.account_id
                AND facts.snapshot_date = labels.snapshot_date
            WHERE facts.snapshot_date = DATE '{test_day}'
            GROUP BY facts.health_band ORDER BY churned_within_90d_pct DESC
            """
        )),
    ]

    lines += hidden_truth_section(con, data_dir)
    lines += [
        "## 6. What data quality caught",
        "",
        *table(query(
            "SELECT stage, measure, row_count FROM gold.dq_summary ORDER BY sort_order, measure"
        )),
        "A consequence worth knowing: about 1.3% of events are rejected at ingest. When the",
        "rejected event is a setup step, the account looks one step behind until the dead letter",
        "is replayed. Seats are read from the licence snapshot instead, and match exactly.",
        "",
    ]
    con.close()
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text("\n".join(lines), encoding="utf-8")
    return report_path


def hidden_truth_section(con, data_dir: Path) -> list[str]:
    """Validation only: compare scores with the simulator's hidden state."""
    hidden_path = data_dir / "ground_truth" / "daily_hidden_state.csv"
    hidden = pd.read_csv(hidden_path, parse_dates=["date"])
    today = con.execute(
        """
        SELECT account_id, snapshot_date, health_score, churn_risk_score
        FROM gold.account_current
        """
    ).df()
    merged = today.merge(hidden[hidden["date"] == hidden["date"].max()], on="account_id")
    rows = [
        ("Health score vs hidden momentum", merged["health_score"].corr(merged["momentum"])),
        ("Churn score vs hidden momentum", merged["churn_risk_score"].corr(merged["momentum"])),
        (
            "Churn score vs true daily churn risk (rank correlation)",
            merged["churn_risk_score"].corr(merged["churn_hazard"], method="spearman"),
        ),
    ]
    frame = pd.DataFrame(rows, columns=["comparison", "correlation"])
    frame["correlation"] = frame["correlation"].round(2)
    return [
        "## 5. Do the scores track the hidden truth? (validation only)",
        "",
        "The simulator keeps a hidden `momentum` per account that drives usage and churn. It is",
        "never exported to the pipeline. Comparing it with our scores shows whether they measure",
        "something real. In a real company this check does not exist; the equivalent is",
        "back-testing against outcomes, as in sections 3 and 4.",
        "",
        *table(frame),
    ]


if __name__ == "__main__":
    print(f"Wrote {write_report()}")
