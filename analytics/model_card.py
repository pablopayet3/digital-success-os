"""Write a model card from the training results.

Synthetic data, fictional company. The card is generated, not hand-written, so
the numbers in it always match the model that is actually in use.
"""

from __future__ import annotations

from pathlib import Path

from common.paths import ROOT

CARD_DIR = ROOT / "docs" / "model-cards"

PURPOSE = {
    "churn": (
        "Rank accounts by their risk of churning in the next 90 days, so the scaled CS "
        "team works the accounts most worth a human conversation. Feeds the "
        "`churn_risk_high` signal and the `at_risk` lifecycle stage."
    ),
    "expansion": (
        "Rank accounts by their likelihood of expanding (more seats or a higher edition) "
        "in the next 90 days, so account owners get a brief only where there is real "
        "evidence. Feeds the `expansion_ready` signal and the `expansion` lifecycle stage."
    ),
}
ACTION = {
    "churn": "the pooled CS team can carry",
    "expansion": "account owners can follow up",
}


def write_model_card(name: str, result: dict, card_dir: Path = CARD_DIR) -> None:
    logistic, boosting = result["logistic"], result["boosting"]
    lines = [
        f"# Model card: {name} model",
        "",
        "Synthetic data, fictional company. Generated by `analytics/model_card.py` on every",
        "training run, so the numbers always match the model in use.",
        "",
        "## Purpose",
        "",
        PURPOSE[name],
        "",
        "## Owner and cadence",
        "",
        "- Owner: Digital Success Portfolio Lead (accountable), with Data Science (builds).",
        "- Retrain: monthly, and whenever the health-score definition or a source table changes.",
        "- Review: precision at the threshold is checked in the monthly operating review.",
        "",
        "## Data",
        "",
        f"- Label: `{result['label']}`, taken from the CRM (churn date, closed-won expansion",
        "  opportunities). Never from the simulator's hidden ground truth.",
        f"- Training snapshots: {', '.join(result['train_days'])} ({result['train_rows']:,} rows,",
        f"  {result['train_positive_rate']:.1%} positive).",
        f"- Test snapshot: {result['test_day']} ({result['test_rows']:,} rows,",
        f"  {result['test_positive_rate']:.1%} positive). Later in time than every training row.",
        "- Features: 23, all from `gold.int_account_daily_health` as it stood on the snapshot",
        "  day (usage, seats, setup, support, NPS, email engagement, edition limits).",
        "  The list and the plain-word explanation of each is in `analytics/features.py`.",
        "",
        "## Performance on the test snapshot",
        "",
        "| Measure | Logistic regression (in use) | Gradient boosting (benchmark) |",
        "|---|---|---|",
        f"| AUC (ranking quality, 0.5 = random) | {logistic['auc']:.3f} | {boosting['auc']:.3f} |",
        f"| Precision in the top 10% | {logistic['precision_at_top_10pct']:.1%} "
        f"| {boosting['precision_at_top_10pct']:.1%} |",
        f"| Recall in the top 10% | {logistic['recall_at_top_10pct']:.1%} "
        f"| {boosting['recall_at_top_10pct']:.1%} |",
        f"| Brier score (lower is better) | {logistic['brier']:.3f} | {boosting['brier']:.3f} |",
        "",
        "Logistic regression is the production model because every score can be explained to",
        "a CSM in plain words (coefficient times distance from average). Gradient boosting is",
        "kept as a benchmark, so we know how much accuracy that explainability costs.",
        "",
        "### Calibration (accounts split into five equal groups by score)",
        "",
        "| Group | Accounts | Predicted | Observed |",
        "|---|---|---|---|",
    ]
    lines += [
        f"| {row['group']} | {row['accounts']} | {row['predicted']:.1%} | {row['observed']:.1%} |"
        for row in result["calibration"]
    ]
    lines += [
        "",
        "## Threshold: chosen by capacity",
        "",
        f"- Capacity: {result['capacity_accounts']} flagged accounts in the pilot segment is what "
        f"{ACTION[name]} at one time (`config/models.yaml`).",
        "- The cut-off is redrawn every day: the score of the account at that rank in the pilot",
        "  segment. Every account at or above it is flagged, in any segment.",
        f"- On the test snapshot the cut-off was a score of {result['threshold']:.3f}, flagging",
        f"  {result['flagged_in_pilot_segment']} accounts in the pilot segment.",
        f"- Precision at the cut-off: {result['precision_at_threshold']:.1%} "
        f"(base rate in the segment: {result['pilot_segment_base_rate']:.1%}).",
        f"- Recall at the cut-off: {result['recall_at_threshold']:.1%}.",
        "",
        "See `docs/decisions/0004-churn-threshold-by-capacity.md` for why the threshold is set",
        "this way.",
        "",
        "## Strongest drivers",
        "",
        "Coefficients on standardised features. Positive raises the score.",
        "",
        "| Feature | Coefficient |",
        "|---|---|",
    ]
    lines += [f"| {d['feature']} | {d['coefficient']:+.3f} |" for d in result["top_drivers"]]
    lines += [
        "",
        "## Known limitations",
        "",
        "- Trained on simulated customers. The patterns are plausible, not real.",
        "- The same accounts appear in the training and test snapshots on different days. The",
        "  split is by time, which is how the model is used, but a stricter test would also",
        "  hold out accounts.",
        "- Only two or three training snapshots: a few hundred positive examples.",
        "- Because the cut-off follows capacity, an account can leave the flagged list without",
        "  getting healthier, simply because others got worse. The score is the measure of risk;",
        "  the flag only says who gets attention first.",
        "- Gradient boosting ranks better than the model in use (see the table). That gap is the",
        "  price of an explanation a CSM can read. Revisit once the team trusts the flags.",
        "- Scores for days inside the training window are in-sample.",
        "- Contact fields are a current snapshot, so they are not used as features.",
        "",
    ]
    card_dir.mkdir(parents=True, exist_ok=True)
    (card_dir / f"{name}.md").write_text("\n".join(lines), encoding="utf-8")
