"""Generate the synthetic world and write the raw files a pipeline would receive.

Synthetic data, fictional company (Lumen Labs / Relay).

Run with:  uv run python run.py data

Writes two folders:
    data/landing/        what the company's systems would export (the pipeline reads this)
    data/ground_truth/   the answer key (hidden traits, labels, injected problems);
                         never read by the pipeline, the models or the agents
"""

from __future__ import annotations

import csv
import json
import shutil
import time
from datetime import date, datetime
from pathlib import Path

import numpy as np

from common.config import load_world_config
from common.paths import DATA_DIR
from synth import mess
from synth.report import build_report
from synth.world import World

NOTICE = "Synthetic data, fictional company (Lumen Labs / Relay). Generated by synth/generate.py.\n"

ACCOUNT_COLUMNS = [
    "account_id", "name", "segment", "coverage_tier", "edition", "products", "seats_licensed",
    "arr", "contract_start", "renewal_date", "region", "industry", "account_owner", "csm",
    "status", "churned_at",
]  # fmt: skip
CONTACT_COLUMNS = [
    "contact_id", "account_id", "full_name", "email", "persona", "role", "consent_status",
    "email_valid", "product_user_id", "last_engaged_at",
]  # fmt: skip
OPPORTUNITY_COLUMNS = [
    "opportunity_id", "account_id", "type", "name", "stage", "amount", "created_at",
    "close_date", "owner", "source",
]  # fmt: skip
LICENSE_COLUMNS = ["date", "account_id", "edition", "seats_licensed", "seats_assigned"]
TICKET_COLUMNS = [
    "ticket_id", "account_id", "contact_id", "created_at", "priority", "category", "subject",
    "body", "status", "resolved_at",
]  # fmt: skip
NPS_COLUMNS = ["response_id", "account_id", "contact_id", "score", "comment", "responded_at"]
EMAIL_COLUMNS = [
    "send_id", "campaign", "subject", "contact_id", "account_id", "sent_at", "delivered",
    "bounced", "opened_at", "clicked_at", "unsubscribed",
]  # fmt: skip
MAILBOX_FIELDS = [
    "message_id", "received_at", "from_email", "from_name", "to_email", "in_reply_to",
    "subject", "body",
]  # fmt: skip
MAILBOX_LABEL_COLUMNS = [
    "message_id", "intent", "sentiment", "secondary_intent", "is_hard", "account_id",
    "contact_id",
]  # fmt: skip


def generate(profile: str | None = None, data_dir: Path = DATA_DIR, verbose: bool = True) -> World:
    """Build the world, simulate the history, write every file. Returns the world."""
    started = time.time()
    cfg = load_world_config(profile)
    world = World(cfg)
    rates = cfg["messy_data"]
    issues = mess.new_issue_log()

    landing, truth = data_dir / "landing", data_dir / "ground_truth"
    for folder in (landing, truth, data_dir / "dead_letter"):
        if folder.exists():
            shutil.rmtree(folder)  # always start from a clean slate
    # A new world makes the old warehouse stale, so it is rebuilt by the next pipeline run.
    (data_dir / "warehouse.duckdb").unlink(missing_ok=True)
    (landing / "events").mkdir(parents=True)
    (landing / "mailbox").mkdir()
    truth.mkdir(parents=True)
    (landing / "_SYNTHETIC_DATA.txt").write_text(NOTICE, encoding="utf-8")

    # Setup events from before the first simulated day.
    backfill_name = f"backfill_before_{world.start_date}.jsonl"
    _write_lines(landing / "events" / backfill_name, map(mess.to_line, world.backfill_events))
    n_events = len(world.backfill_events)

    # One file of product events per simulated day.
    late = rates["late_arriving_day"]
    held_back: list[str] = []
    for day_index in range(cfg["calendar"]["history_days"]):
        out = world.step()
        n_events += len(out.events)
        if rates["enabled"]:
            mess_rng = np.random.default_rng([world.seed, 2, day_index])
            lines = mess.messy_event_lines(out.events, mess_rng, rates, issues)
            # One day's events mostly arrive late, inside the file of a later day.
            if day_index == late["day_index"]:
                keep = round(len(lines) * (1 - late["share_late"]))
                lines, held_back = lines[:keep], lines[keep:]
                issues["late_arriving"] = {
                    "event_date": out.date.isoformat(),
                    "delay_days": late["delay_days"],
                    "late_events": len(held_back),
                }
            elif day_index == late["day_index"] + late["delay_days"]:
                lines += held_back
        else:
            lines = [mess.to_line(event) for event in out.events]
        _write_lines(landing / "events" / f"{out.date}.jsonl", lines)

    row_counts = {"product events (incl. backfill)": n_events}
    row_counts.update(write_snapshots(world, landing, issues))
    write_ground_truth(world, truth, issues)

    report = build_report(world, row_counts, issues)
    (truth / "generation_report.md").write_text(report, encoding="utf-8")
    if verbose:
        print(report)
        print(f"Done in {time.time() - started:.0f}s. Files are in {data_dir}")
    return world


def write_snapshots(world: World, landing: Path, issues: dict) -> dict[str, int]:
    """Write the CRM, licence, support, NPS, email and mailbox files as they stand today."""
    today = world.last_day
    rates = world.cfg["messy_data"]
    live_accounts = [a for a in world.accounts if a.contract_start <= today]

    account_rows = [
        {**vars(a), "products": "|".join(a.products)} for a in live_accounts
    ]
    contact_rows = [vars(c) for a in live_accounts for c in a.contacts]
    if rates["enabled"]:
        contact_rows = mess.messy_contact_rows(contact_rows, rates, issues)

    # A ticket is resolved once its resolution time has passed; until then it is waiting.
    end_of_today = datetime(today.year, today.month, today.day, 23, 59, 59)
    ticket_rows = []
    for ticket in world.tickets:
        resolved = ticket["resolves_at"] <= end_of_today
        ticket_rows.append(
            {
                **ticket,
                "status": "resolved" if resolved else ticket["waiting_status"],
                "resolved_at": ticket["resolves_at"].replace(microsecond=0) if resolved else None,
            }
        )

    _write_csv(landing / "crm_accounts.csv", account_rows, ACCOUNT_COLUMNS)
    _write_csv(landing / "crm_contacts.csv", contact_rows, CONTACT_COLUMNS)
    _write_csv(landing / "crm_opportunities.csv", world.opportunities, OPPORTUNITY_COLUMNS)
    _write_csv(landing / "licenses.csv", world.license_rows, LICENSE_COLUMNS)
    _write_csv(landing / "tickets.csv", ticket_rows, TICKET_COLUMNS)
    _write_csv(landing / "nps.csv", world.nps, NPS_COLUMNS)
    _write_csv(landing / "email_engagement.csv", world.email_sends, EMAIL_COLUMNS)
    for message in world.mailbox:
        payload = {field: _fmt(message[field]) for field in MAILBOX_FIELDS}
        path = landing / "mailbox" / f"{message['message_id']}.json"
        path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    return {
        "accounts": len(account_rows),
        "contacts": len(contact_rows),
        "opportunities": len(world.opportunities),
        "license rows (account x day)": len(world.license_rows),
        "tickets": len(ticket_rows),
        "NPS responses": len(world.nps),
        "emails sent": len(world.email_sends),
        "mailbox replies": len(world.mailbox),
    }


def write_ground_truth(world: World, truth: Path, issues: dict) -> None:
    """Write the answer key. Used only to validate models and classifiers, never as input."""
    latent_rows = [
        {
            "account_id": a.account_id,
            "engagement_propensity": round(a.engagement, 4),
            "fit": round(a.fit, 4),
            "growth": round(a.growth, 4),
            "docs_need": round(a.docs_need, 4),
            "setup_drive": round(a.setup_drive, 4),
            "assist_affinity": round(a.assist_affinity, 4),
        }
        for a in world.accounts
    ]
    expansions: dict[str, list[date]] = {}
    for opportunity in world.opportunities:
        if opportunity["type"] == "expansion":
            expansions.setdefault(opportunity["account_id"], []).append(opportunity["close_date"])
    outcome_rows = [
        {
            "account_id": a.account_id,
            "signed_up_on": a.contract_start,
            "churned_at": a.churned_at,
            "first_expanded_at": min(expansions.get(a.account_id, [None])),
            "n_expansions": len(expansions.get(a.account_id, [])),
        }
        for a in world.accounts
    ]
    contact_rows = [
        {"contact_id": c.contact_id, "affinity": round(c.affinity, 4), "has_left": c.has_left}
        for a in world.accounts
        for c in a.contacts
    ]

    _write_csv(truth / "latents.csv", latent_rows, list(latent_rows[0]))
    _write_csv(truth / "outcomes.csv", outcome_rows, list(outcome_rows[0]))
    _write_csv(truth / "contacts_hidden.csv", contact_rows, list(contact_rows[0]))
    _write_csv(truth / "daily_hidden_state.csv", world.hidden_rows, list(world.hidden_rows[0]))
    _write_csv(truth / "mailbox_labels.csv", world.mailbox_labels, MAILBOX_LABEL_COLUMNS)
    _write_csv(truth / "ticket_labels.csv", world.ticket_labels, ["ticket_id", "tone"])
    (truth / "injected_issues.json").write_text(json.dumps(issues, indent=2), encoding="utf-8")
    world.save(truth / "world_state.pkl")


# --- Small file helpers -------------------------------------------------------------------


def _fmt(value):
    """Write values the same way everywhere: ISO dates, true/false, empty for missing."""
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, datetime):
        return value.strftime("%Y-%m-%dT%H:%M:%SZ")
    if isinstance(value, date):
        return value.isoformat()
    return value


def _write_csv(path: Path, rows: list[dict], columns: list[str]) -> None:
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(columns)
        for row in rows:
            writer.writerow([_fmt(row[column]) for column in columns])


def _write_lines(path: Path, lines) -> None:
    with open(path, "w", newline="", encoding="utf-8") as f:
        for line in lines:
            f.write(line + "\n")


if __name__ == "__main__":
    generate()
